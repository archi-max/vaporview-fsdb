#!/bin/sh
# SPDX-License-Identifier: MIT
# Builds the native Wisp helper core: sh build.sh <outdir>  ->  <outdir>/wisp-helper
# (GCC 11 or newer, -std=gnu++17; zstd's decompressor with cc; links -lz -pthread.)
# Reads WCZ files, and FSDB files directly through the converter's reader in convert/fsdb/ (no copy here; without it, WCZ only).
set -eu
OUT=${1:?usage: sh build.sh <outdir>}
D=$(cd "$(dirname "$0")" && pwd -P)
mkdir -p "$OUT"
CXX=${CXX:-c++}
CC=${CC:-cc}
OPT=${OPT:--O2}
# the compiler floor, checked first: C++17 with floating-point std::to_chars (GCC 11 or newer; clang with such a library)
printf '#include <charconv>\n#include <system_error>\nint main(){char b[40];double d=1.5;return std::to_chars(b,b+40,d,std::chars_format::scientific).ec==std::errc{}?0:1;}\n' > "$OUT/cc-check.cpp"
$CXX -std=gnu++17 "$OUT/cc-check.cpp" -o "$OUT/cc-check" 2> "$OUT/cc-check.log" || { echo "$CXX cannot build the helper: it needs C++17 with floating-point std::to_chars (GCC 11 or newer). Compiler output: $OUT/cc-check.log"; exit 2; }
# the WCZ reader headers: the repository's include/ (helper/ sits next to it), or WCZ_INCLUDE
WCZ_INC=${WCZ_INCLUDE:-$D/../include}
[ -f "$WCZ_INC/wcz_seg.h" ] || { echo "no WCZ headers in $WCZ_INC (set WCZ_INCLUDE)"; exit 2; }
# the in-place reader (sigread) and the planner, compiled from the repository's converter directory (helper/ carries no copy):
# WISP_CONVERTER_DIR (default ../convert/<format>), WISP_SIGREAD_DIR (default its src/)
CONVD=${WISP_CONVERTER_DIR:-$D/../convert/fsdb}
SRD=${WISP_SIGREAD_DIR:-$CONVD/src}
DIRECT=0; DEF=; EXTRA=
# (sigread.h is header-only; only the planner is compiled separately. The WCZ declaration form is lib/addon/sigread_wcz.h)
if [ -f "$SRD/sigread.h" ] && [ -f "$CONVD/fplan/fplan.cpp" ]; then DIRECT=1; DEF="-DWISP_DIRECT -I$CONVD/fplan -I$CONVD/src"; EXTRA="$OUT/fplan.o"; fi
echo "direct FSDB read: $([ $DIRECT = 1 ] && echo "on ($SRD)" || echo "off (no sigread.h in $SRD)")"
SIDE=$CONVD/side
if [ $DIRECT = 1 ]; then
  # computed rows (lib/addon/window_compute.cpp.inc): the window run's headers in convert/fsdb/side, and its rule words built in
  [ -f "$SIDE/window_run.h" ] && [ -f "$SIDE/proven-words.txt" ] && [ -f "$SIDE/window-safe-words.txt" ] || { echo "direct FSDB read needs $SIDE (window_run.h, proven-words.txt, window-safe-words.txt)"; exit 2; }
  { echo "// generated by helper/build.sh from convert/fsdb/side/proven-words.txt and window-safe-words.txt"
    printf 'static const char *const kProvenWords = R"WCZWORDS('; cat "$SIDE/proven-words.txt"; echo ')WCZWORDS";'
    printf 'static const char *const kWindowSafeWords = R"WCZWORDS('; cat "$SIDE/window-safe-words.txt"; echo ')WCZWORDS";'; } > "$OUT/window_words.h"
  DEF="$DEF -I$SIDE -I$OUT"
fi
INC="-I$D/lib/shim -I$D/lib/src -I$D/lib/addon -I$WCZ_INC -I$D/lib/third_party/zstd/lib -I$SRD $DEF"
echo "cc zstddec.c"
$CC $OPT -c "$D/lib/third_party/zstd/zstddec.c" -I"$D/lib/third_party/zstd/lib" -o "$OUT/zstddec.o"
P2=; P3=
if [ $DIRECT = 1 ]; then
  echo "c++ planner"
  $CXX -std=gnu++17 $OPT -pthread -w -I"$CONVD/fplan" -I"$D/lib/third_party/zstd/lib" -c "$CONVD/fplan/fplan.cpp" -o "$OUT/fplan.o" &
  P3=$!
fi
# the library: one translation unit, registered through the shim (lib/addon/wcb_reader.cpp)
echo "c++ lib/addon/wcb_reader.cpp"
$CXX -std=gnu++17 $OPT -pthread $INC -c "$D/lib/addon/wcb_reader.cpp" -o "$OUT/lib.o" &
P1=$!
# the build id: the sha256 of this core's sources and build script
BID=$(cat "$D/build.sh" "$D"/src/*.cpp "$D"/src/*.h | { sha256sum 2>/dev/null || shasum -a 256; } | cut -c1-16)
echo "build id $BID"
echo "c++ src/main.cpp"
$CXX -std=gnu++17 $OPT -pthread -Wall -Wextra -Wno-unused-parameter $INC -I"$D/src" -DWISP_BUILD_ID="\"$BID\"" -c "$D/src/main.cpp" -o "$OUT/main.o"
wait $P1; [ -z "$P2" ] || wait $P2; [ -z "$P3" ] || wait $P3
$CXX -pthread -o "$OUT/wisp-helper" "$OUT/main.o" "$OUT/lib.o" $EXTRA "$OUT/zstddec.o" -lz
echo "built $OUT/wisp-helper"
