#!/bin/bash
# vscode-port: copy cmux's waveform page modules (Resources/vaporview/cmux-*.js, GPL-3.0) into media/cmux/,
# unchanged apart from a header line naming where they came from, and generate media/cmux/strings.js (the
# English page strings from Sources/Panels/WaveformViewerStrings.swift) and media/cmux/cmux.css (the pane,
# menu, dialog and toast styles from Resources/vaporview/index.html).
#
# The modules run inside the VS Code webview next to VaporView's webview.js. media/cmux/bridge.js gives them
# the window.cmuxWaveform.host object cmux's host.js gave them, backed by RPC to the extension
# (src/cmux/bridge_host.ts, src/cmux/data.ts), so no module needs editing.
#
# Usage: tools/import-cmux-modules.sh [cmux repo] [ref]   (defaults: ../cmux, the pinned ref below)
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
CMUX="${1:-$HERE/../cmux}"
REF="${2:-45a845a1ab407ba9399a00adc046545bb467e650}"   # origin/sv-editor on 2026-11-24
OUT="$HERE/media/cmux"
mkdir -p "$OUT"
MODULES="cmux-ui cmux-expr cmux-enum cmux-formats cmux-textmatch cmux-debugger-text cmux-debugger-commits cmux-debugger
cmux-riscv-disasm cmux-machine-core cmux-sequence cmux-machine cmux-fsm cmux-trace cmux-trace-ui"
for m in $MODULES; do
  {
    echo "// vscode-port: copied unchanged from cmux (GPL-3.0) Resources/vaporview/$m.js @ ${REF:0:11} by tools/import-cmux-modules.sh; edit there and re-import."
    git -C "$CMUX" show "$REF:Resources/vaporview/$m.js"
  } > "$OUT/$m.js"
done
git -C "$CMUX" show "$REF:Resources/vaporview/LICENSE" > "$OUT/LICENSE"

# Page strings: "key": String(localized: "...", defaultValue: "...") -> { key: defaultValue }.
git -C "$CMUX" show "$REF:Sources/Panels/WaveformViewerStrings.swift" | python3 -I -c '
import re, sys, json
s = sys.stdin.read()
pairs = re.findall(r"\"([A-Za-z0-9_.]+)\":\s*String\(\s*localized:\s*\"[^\"]*\",\s*defaultValue:\s*\"((?:[^\"\\\\]|\\\\.)*)\"", s, re.S)
d = {k: json.loads("\"" + v + "\"") for k, v in pairs}
# The UI never names cmux: strings that do are reworded here, and an unknown one stops the import.
REWORD = {
    "cmux didn\u2019t hear back": "The viewer didn\u2019t hear back",
    "cmux didn'"'"'t hear back": "The viewer didn'"'"'t hear back",
    "cmux has no record of this file": "The viewer has no record of this file",
    # vscode-port: , the extension is named VaporView FSDB
    "Vaporview Session": "VaporView FSDB Session",
    "Vaporview Readme": "VaporView FSDB Readme",
    "not a VaporView session": "not a VaporView FSDB session",
}
for k, v in d.items():
    for old, new in REWORD.items():
        v = v.replace(old, new)
    if re.search(r"\bcmux\b", v, re.I):
        sys.exit("import-cmux-modules: page string " + k + " names cmux; add a rewording to REWORD: " + v)
    d[k] = v
print("// vscode-port: generated by tools/import-cmux-modules.sh from cmux (GPL-3.0) Sources/Panels/WaveformViewerStrings.swift.")
print("// Much of the English text is VaporView'"'"'s (https://github.com/Lramseyer/vaporview, GPL-3.0). Do not edit; re-import.")
print("window.cmuxPageStrings = " + json.dumps(d, indent=0, ensure_ascii=False, sort_keys=True) + ";")
' > "$OUT/strings.js"

# Styles for the panes and widgets the modules draw (everything from the FSM pane rules on; the netlist,
# status strip and iframe rules are cmux's host page, which VS Code replaces).
git -C "$CMUX" show "$REF:Resources/vaporview/index.html" | python3 -I -c '
import sys
html = sys.stdin.read()
css = html.split("<style>", 1)[1].split("</style>", 1)[0]
start = css.index("/* State machine pane")
lines = [l for l in css[start:].splitlines() if "#viewer" not in l]
print("/* vscode-port: generated by tools/import-cmux-modules.sh from cmux (GPL-3.0) Resources/vaporview/index.html. Do not edit; re-import. */")
print("\n".join(l[4:] if l.startswith("    ") else l for l in lines))
' > "$OUT/cmux.css"
echo "imported $(echo $MODULES | wc -w | tr -d " ") modules from $REF into $OUT"
