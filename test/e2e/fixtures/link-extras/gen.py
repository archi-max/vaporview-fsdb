# Generates xtb.sv and xtb.vcd (synthetic, public): the design and dump for the Split > By Declared Dimensions and
# Add All Signals in Scope e2e tests (bridge-extras.test.cjs). Run: python3 gen.py
# SPDX-License-Identifier: GPL-3.0-or-later
N_MID, N_WIDE = 60, 140
sv = ["// Synthetic design for bridge-extras.test.cjs; generated by gen.py.",
      "module x_small(input logic clk);",
      "  logic [1:0][3:0] pa;        // 8 bits, two elements of 4",
      "  logic [0:2][7:0] asc;       // 24 bits, ascending outer index",
      "  logic [2:0][1:0][1:0] p3;   // 12 bits, three dimensions",
      "  logic [7:0] plain;          // one dimension: nothing declared to split by",
      "  always_ff @(posedge clk) begin pa <= ~pa; asc <= {asc[1:0], asc[2]}; p3 <= p3 + 1; plain <= plain + 1; end",
      "endmodule",
      "module x_mid(input logic clk);"]
sv += [f"  logic m{i};" for i in range(N_MID)]
sv += ["endmodule", "module x_wide(input logic clk);"]
sv += [f"  logic w{i};" for i in range(N_WIDE)]
sv += ["endmodule",
       "module xtb;",
       "  logic clk = 0;",
       "  x_small u_small(.clk);",
       "  x_mid u_mid(.clk);",
       "  x_wide u_wide(.clk);",
       "  always #5 clk = ~clk;",
       "endmodule", ""]
open("xtb.sv", "w").write("\n".join(sv))

ids = iter(range(10000))
CHARS = [chr(c) for c in range(33, 127) if chr(c) not in "$#"]
def ident():
    n = next(ids); s = ""
    while True:
        s += CHARS[n % len(CHARS)]; n //= len(CHARS)
        if n == 0: return s
v = ["$timescale 1ns $end", "$scope module xtb $end"]
clk = ident(); v.append(f"$var reg 1 {clk} clk $end")
small = {"pa": (8, ident()), "asc": (24, ident()), "p3": (12, ident()), "plain": (8, ident())}
v += ["$scope module u_small $end", f"$var wire 1 {clk} clk $end"]
v += [f"$var wire {w} {i} {n} [{w-1}:0] $end" for n, (w, i) in small.items()]
v.append("$upscope $end")
mid = [ident() for _ in range(N_MID)]
v += ["$scope module u_mid $end", f"$var wire 1 {clk} clk $end"] + [f"$var wire 1 {i} m{k} $end" for k, i in enumerate(mid)] + ["$upscope $end"]
wide = [ident() for _ in range(N_WIDE)]
v += ["$scope module u_wide $end", f"$var wire 1 {clk} clk $end"] + [f"$var wire 1 {i} w{k} $end" for k, i in enumerate(wide)] + ["$upscope $end"]
v += ["$upscope $end", "$enddefinitions $end"]
vals = {"pa": [0x5A, 0xA5], "asc": [0x123456, 0x345612], "p3": [0x9C3, 0x9C4], "plain": [1, 2]}
for t in range(2):
    v.append(f"#{t * 10}")
    v.append(f"{t % 2}{clk}" if t else f"0{clk}")
    for n, (w, i) in small.items():
        v.append("b" + format(vals[n][t], f"0{w}b") + " " + i)
    if t == 0:
        v += [f"0{i}" for i in mid + wide]
v.append("#20")
open("xtb.vcd", "w").write("\n".join(v) + "\n")
